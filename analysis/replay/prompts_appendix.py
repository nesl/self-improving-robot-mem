#!/usr/bin/env python3
"""Verbatim day-14 prompts for the appendix, recorded from a replay of the real cells.

    PYTHONPATH=src python3 analysis/replay/prompts_appendix.py

Each arm's hh_s2_t03 cell is replayed from the response cache up to day 14 through overnight_wave,
so the notes and the record are what the run had on that day. Recorded: the first room-choice
prompt of day 14, the first answer prompt of day 14 (asked only after a search fails), and every
nightly-update call of night 14. Writes $OUT_DIR/prompts_appendix.md (the paper's copy is results/self_improve/paper/prompts_appendix.md).
"""
import json
import os
import pathlib
import re
import sys
import tempfile

from baselines.patrol.llm import LLMClient
from self_improve import overnight_wave as ow
from self_improve.frozen_household import FrozenHousehold

R = pathlib.Path("results/self_improve")
TEN = R / "varied_homes/ten_homes/banks"
# The response cache is not in the public release; point $LLM_CACHE at a copy of it.
CACHE = pathlib.Path(os.environ.get("LLM_CACHE", "llm_cache/self_improve"))
DAY = 14
ARMS = [  # (label in the paper, arm, wave the replay matches, questions a day)
    ("claim store", "incremental edits", "wave_reasons_first", 24),
    ("log and notes", "the log and notes about the routine", "wave_reasons_first", 24),
    ("log only", "log only, no notes", "wave_log_only", 8),
    ("ACE as published", "ACE as published", "wave_reasons_first", 24),
    ("MemGPT as published", "MemGPT as published", "wave_reasons_first", 24),
]
DAY_RE = re.compile(r"(?:on day|It is day) (\d+) at")


class Recorder(LLMClient):
    def __init__(self):
        super().__init__(CACHE, replay_only=True)
        self.misses, self.calls, self.day = 0, [], -1

    def complete(self, messages, schema, max_tokens):
        user = next(m["content"] for m in messages if m["role"] == "user")
        props = set((schema or {}).get("properties", {}))
        kind = "choice" if "room" in props else "answer" if "location" in props else "night"
        if kind != "night":
            m = DAY_RE.search(user)
            self.day = int(m.group(1)) if m else self.day
        text, usage = super().complete(messages, schema, max_tokens)
        self.misses += text is None
        if self.day == DAY:
            self.calls.append({"kind": kind, "messages": messages, "schema": schema,
                               "max_tokens": max_tokens, "reply": text})
        return text, usage


def block(title, call):
    out = [f"#### {title}", "", f"max_tokens {call['max_tokens']}; reply schema:", "",
           "```json", json.dumps(call["schema"], indent=1), "```", ""]
    for m in call["messages"]:
        out += [f"**{m['role']}**", "", "```text", m["content"], "```", ""]
    out += ["**the model's reply (from the cache)**", "", "```json", call["reply"] or "(no reply)", "```", ""]
    return out


def main() -> int:
    md = ["# Prompts, verbatim (hh_s2_t03, day 14)", "",
          "Generated by `results/self_improve/camera_ready/scripts/prompts_appendix.py`, which replays each arm's",
          "real cell from the response cache up to day 14 and records what was sent. Day 14 is the first day of",
          "the illness. Three prompts per arm: the first room choice of the day, the first answer (asked only",
          "when the three-room search fails) and the nightly update after day 14. The log-only arm has no",
          "nightly update.", ""]
    for label, arm, wave, qpd in ARMS:
        rec = Recorder()
        with tempfile.TemporaryDirectory() as d:
            try:
                ow.run_one_arm(FrozenHousehold(TEN / "hh_s2_t03.jsonl"), arm, rec,
                               pathlib.Path(d) / "w" / "cells" / "a" / "h", DAY, qpd, 3, 0)
            except AssertionError as e:
                print(arm, "gate:", str(e)[:120], file=sys.stderr)
        first = lambda k: next((c for c in rec.calls if c["kind"] == k), None)  # noqa: E731
        nights = [c for c in rec.calls if c["kind"] == "night"]
        md += [f"## {label} (`{arm}`; replay of `{wave}`, {qpd} questions a day; "
               f"{rec.misses} calls missing from the cache)", ""]
        for title, call in (("Room choice", first("choice")), ("Answer", first("answer"))):
            md += block(title, call) if call else [f"#### {title}", "", "(none on this day)", ""]
        for i, call in enumerate(nights, 1):
            md += block(f"Nightly update, call {i} of {len(nights)}", call)
        if not nights:
            md += ["#### Nightly update", "", "(this arm writes nothing at night)", ""]
        print(label, "misses", rec.misses, "calls on day 14", len(rec.calls), file=sys.stderr)
    out = pathlib.Path(os.environ.get("OUT_DIR", "out")) / "prompts_appendix.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(md))
    print("wrote", out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
